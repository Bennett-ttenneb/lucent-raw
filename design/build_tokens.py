#!/usr/bin/env python3
"""Generate tokens.css and tailwind.preset.cjs from tokens.json. Run after any token change."""
import json
t = json.load(open("tokens.json", encoding="utf-8"))
L = [":root {", "  color-scheme: dark;"]
for k, v in t["color"].items(): L.append(f"  --color-{k}: {v};")
L.append(f"  --font-sans: {t['font']['sans']};")
L.append(f"  --font-mono: {t['font']['mono']};")
for k, v in t["type"].items():
    L += [f"  --text-{k}-size: {v['size']}px;", f"  --text-{k}-line: {v['line']}px;", f"  --text-{k}-weight: {v['weight']};"]
for i, v in enumerate(t["space"]): L.append(f"  --space-{i}: {v}px;")
for k, v in t["radius"].items(): L.append(f"  --radius-{k}: {v}px;")
for k, v in t["shadow"].items(): L.append(f"  --shadow-{k}: {v};")
for k, v in t["motion"].items(): L.append(f"  --motion-{k}: {v};")
for k, v in t["layout"].items():
    if isinstance(v, int): L.append(f"  --layout-{k}: {v}px;")
L.append("}")
L += ["@media (prefers-reduced-motion: reduce) { :root { --motion-fast: 0ms; --motion-base: 0ms; } }"]
open("tokens.css", "w", encoding="utf-8").write("\n".join(L) + "\n")

colors = {k: f"var(--color-{k})" for k in t["color"]}
fs = {k: [f"var(--text-{k}-size)", {"lineHeight": f"var(--text-{k}-line)", "fontWeight": f"var(--text-{k}-weight)"}] for k in t["type"]}
preset = {
  "theme": {"extend": {
    "colors": colors, "fontSize": fs,
    "fontFamily": {"sans": ["var(--font-sans)"], "mono": ["var(--font-mono)"]},
    "borderRadius": {k: f"var(--radius-{k})" for k in t["radius"]},
    "boxShadow": {k: f"var(--shadow-{k})" for k in t["shadow"]},
    "spacing": {"panel-l": "var(--layout-left-panel)", "panel-r": "var(--layout-right-panel)",
                "panel-h": "var(--layout-panel-header)", "toolbar": "var(--layout-toolbar)",
                "filmstrip": "var(--layout-filmstrip)"},
    "transitionDuration": {"fast": "var(--motion-fast)", "base": "var(--motion-base)"},
  }}
}
open("tailwind.preset.cjs", "w", encoding="utf-8").write(
  "// Generated by build_tokens.py from tokens.json. Use: presets: [require('./replica/design/tailwind.preset.cjs')]\n"
  "module.exports = " + json.dumps(preset, indent=2) + ";\n")
print("wrote tokens.css, tailwind.preset.cjs")
