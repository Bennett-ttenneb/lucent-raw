import { expect, open, test } from './helpers'

test.describe('F30 stacks', () => {
  test('ST1 Ctrl+G stacks the selected photos closed under the first one, S opens and closes the stack, Ctrl+Shift+G takes it apart', async ({ page }) => {
    await open(page)
    const cells = page.getByRole('gridcell')
    const before = await cells.count()
    await cells.nth(0).click()
    await cells.nth(2).click({ modifiers: ['Shift'] })
    await page.keyboard.press('Control+g')
    await expect(page.getByRole('status').filter({ hasText: 'Stacked 3 photos.' })).toBeVisible()
    await expect(page.getByRole('gridcell', { name: /stack of 3 \(closed\)/ })).toHaveCount(1)
    await expect(page.getByRole('grid', { name: /94 photos/ })).toBeVisible() // 96 less the two hidden under the top
    await page.keyboard.press('s')
    await expect(page.getByRole('gridcell', { name: /stack of 3$/ })).toHaveCount(3)
    await expect(page.getByRole('grid', { name: /96 photos/ })).toBeVisible()
    await page.keyboard.press('s')
    await expect(page.getByRole('gridcell', { name: /stack of 3 \(closed\)/ })).toHaveCount(1)
    await page.keyboard.press('Control+Shift+g')
    await expect(page.getByRole('gridcell', { name: /stack of/ })).toHaveCount(0)
    await expect(page.getByRole('grid', { name: /96 photos/ })).toBeVisible()
    expect(before).toBeGreaterThan(3)
  })

  test('ST2 the Photo menu stacks, takes one photo out, and opens and closes every stack; one photo alone cannot be stacked', async ({ page }) => {
    await open(page)
    const cells = page.getByRole('gridcell')
    await cells.nth(0).click()
    await page.getByRole('menuitem', { name: 'Photo' }).click()
    await page.getByRole('menuitem', { name: 'Group into a stack' }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Select two or more photos' })).toBeVisible()
    await cells.nth(1).click({ modifiers: ['Shift'] })
    await page.getByRole('menuitem', { name: 'Photo' }).click()
    await page.getByRole('menuitem', { name: 'Group into a stack' }).click()
    await expect(page.getByRole('gridcell', { name: /stack of 2 \(closed\)/ })).toHaveCount(1)
    await page.getByRole('menuitem', { name: 'Photo' }).click()
    await page.getByRole('menuitem', { name: 'Open all stacks' }).click()
    await expect(page.getByRole('gridcell', { name: /stack of 2$/ })).toHaveCount(2)
    await page.getByRole('gridcell', { name: /stack of 2$/ }).nth(1).click()
    await page.getByRole('menuitem', { name: 'Photo' }).click()
    await page.getByRole('menuitem', { name: 'Take out of the stack' }).click()
    await expect(page.getByRole('gridcell', { name: /stack of/ })).toHaveCount(0)
  })
  test('ST3 Auto-stack by capture time stacks photos taken close together and says how many stacks it made', async ({ page }) => {
    await open(page)
    await page.getByRole('menuitem', { name: 'Photo' }).click()
    await page.getByRole('menuitem', { name: /Auto-stack \(by time or by look\)/ }).click()
    const dlg = page.getByRole('dialog', { name: 'Auto-stack' })
    await dlg.getByLabel('Stack photos taken no more than').selectOption({ label: '5 minutes' })
    await dlg.getByRole('button', { name: 'Stack' }).click()
    await expect(page.getByRole('status').filter({ hasText: /Made \d+ stacks? of \d+ photos?\./ })).toBeVisible()
    await expect(page.getByRole('gridcell', { name: /stack of \d+ \(closed\)/ }).first()).toBeVisible()
  })
  test('ST4 Auto-stack by look stacks photos that look alike, and says so when it finds none', async ({ page }) => {
    await open(page)
    await page.getByRole('menuitem', { name: 'Photo' }).click()
    await page.getByRole('menuitem', { name: /Auto-stack \(by time or by look\)/ }).click()
    const dlg = page.getByRole('dialog', { name: 'Auto-stack' })
    await dlg.getByRole('button', { name: 'By look (near duplicates)' }).click()
    await dlg.getByRole('button', { name: 'Stack' }).click()
    await expect(page.getByRole('status').filter({ hasText: /Made 1 stack of \d+ photos\./ })).toBeVisible()
    await page.getByRole('menuitem', { name: 'Photo' }).click()
    await page.getByRole('menuitem', { name: /Auto-stack \(by time or by look\)/ }).click()
    await dlg.getByRole('button', { name: 'By look (near duplicates)' }).click()
    await dlg.getByRole('button', { name: 'Stack' }).click()
    await expect(page.getByRole('status').filter({ hasText: 'No photos that look alike were found.' })).toBeVisible()
  })
})