import { cells, expect, open, test } from './helpers'
import type { Page } from '@playwright/test'

const bar = (page: Page) => page.getByRole('search')
const saved = (page: Page) => bar(page).getByRole('group', { name: 'Saved filters' })

test.describe('F26 library: gaps in the must-have list', () => {
  test('LG1 a filter can be kept under a name, cleared, and brought back with one choice, and it is still there after a reload', async ({ page }) => {
    await open(page)
    const all = await cells(page).count()
    await bar(page).getByRole('tab', { name: 'Attribute' }).click()
    await bar(page).getByLabel('Flag').selectOption('pick')
    await expect.poll(async () => cells(page).count()).toBeLessThan(all)
    await saved(page).getByRole('button', { name: 'Keep this filter…' }).click()
    await saved(page).getByLabel('Name for this filter').fill('Just picks')
    await saved(page).getByRole('button', { name: 'Keep', exact: true }).click()
    await expect(saved(page).getByRole('combobox')).toHaveValue('Just picks')
    await bar(page).getByRole('tab', { name: 'None' }).click()
    await expect.poll(async () => cells(page).count()).toBe(all)
    await saved(page).getByRole('combobox').selectOption('Just picks')
    await expect(bar(page).getByLabel('Flag')).toHaveValue('pick')
    await expect.poll(async () => cells(page).count()).toBeLessThan(all)
    await page.reload()
    await expect(saved(page).getByRole('combobox').locator('option', { hasText: 'Just picks' })).toHaveCount(1)
  })

  test('LG2 an empty filter or an empty name is refused in words; a saved filter can be deleted', async ({ page }) => {
    await open(page)
    await saved(page).getByRole('button', { name: 'Keep this filter…' }).click()
    await saved(page).getByLabel('Name for this filter').fill('Nothing')
    await saved(page).getByRole('button', { name: 'Keep', exact: true }).click()
    await expect(saved(page).getByRole('alert')).toContainText('nothing to keep')
    await saved(page).getByRole('button', { name: 'Cancel' }).click()
    await bar(page).getByRole('tab', { name: 'Attribute' }).click()
    await bar(page).getByLabel('Rating at least').selectOption('3')
    await saved(page).getByRole('button', { name: 'Keep this filter…' }).click()
    await saved(page).getByRole('button', { name: 'Keep', exact: true }).click()
    await expect(saved(page).getByRole('alert')).toContainText('Give it a name')
    await saved(page).getByLabel('Name for this filter').fill('Threes')
    await saved(page).getByRole('button', { name: 'Keep', exact: true }).click()
    await saved(page).getByRole('button', { name: /^Delete/ }).click()
    await expect(saved(page).getByRole('combobox').locator('option', { hasText: 'Threes' })).toHaveCount(0)
  })
})

test.describe('F26 library: edited and not edited', () => {
  test('LG3 the Attribute tab can show only the photos that have edits, or only those without, so they can be selected for export', async ({ page }) => {
    await open(page)
    const all = 96 // the demo catalog
    const grid = (n: number) => expect(page.getByRole('grid', { name: new RegExp(`^Photo grid, ${n} photos?`) })).toBeVisible()
    // edit one photo
    await cells(page).first().click()
    await page.getByRole('tab', { name: 'Develop' }).click()
    const box = page.getByRole('textbox', { name: 'Exposure value', exact: true })
    await box.click()
    await box.fill('1')
    await box.press('Enter')
    await page.getByRole('tab', { name: 'Library' }).click()
    await bar(page).getByRole('tab', { name: 'Attribute' }).click()
    await bar(page).getByLabel('Edits').selectOption('yes')
    await grid(1)
    // Select all and Export now carry only the edited photo
    await cells(page).first().click()
    await page.keyboard.press('Control+a')
    await page.getByRole('button', { name: 'Export…' }).click()
    await expect(page.getByRole('dialog', { name: 'Export photos' }).getByText('Exporting 1 photo.')).toBeVisible()
    await page.getByRole('dialog', { name: 'Export photos' }).getByRole('button', { name: 'Cancel' }).click()
    await bar(page).getByLabel('Edits').selectOption('no')
    await grid(all - 1)
    await bar(page).getByLabel('Edits').selectOption('')
    await grid(all)
    // the choice can be saved with the others
    await bar(page).getByLabel('Edits').selectOption('yes')
    await saved(page).getByRole('button', { name: 'Keep this filter…' }).click()
    await saved(page).getByLabel('Name for this filter').fill('Edited only')
    await saved(page).getByRole('button', { name: 'Keep', exact: true }).click()
    await bar(page).getByRole('tab', { name: 'None' }).click()
    await grid(all)
    await saved(page).getByRole('combobox').selectOption('Edited only')
    await expect(bar(page).getByLabel('Edits')).toHaveValue('yes')
  })
})

test.describe('F26 import: naming, folders and move', () => {
  const importBtn = (page: Page) => page.getByRole('dialog').getByRole('button', { name: /^Import/ }).last()
  test('LG4 copy and move offer a file name pattern and a folder pattern; leaving in place does not, and the choices are sent', async ({ page }) => {
    await open(page)
    await page.getByRole('button', { name: 'Import…' }).click()
    const dlg = page.getByRole('dialog')
    await dlg.getByRole('button', { name: 'Choose folder…' }).click()
    await expect(dlg.getByLabel('File names')).toHaveCount(0)
    await dlg.getByRole('radio', { name: /Move into a folder/ }).check()
    await expect(dlg.getByLabel('File names')).toHaveValue('{name}')
    await expect(dlg.getByLabel('Folders')).toHaveValue('YYYY-MM-DD')
    await expect(dlg.getByText(/only then is the original removed/)).toBeVisible()
    await expect(importBtn(page)).toBeDisabled()
    await dlg.getByLabel('File names').fill('{date}_{seq}')
    await dlg.getByLabel('Folders').selectOption('YYYY/MM/DD')
    await dlg.getByRole('button', { name: 'Choose destination…' }).click()
    await importBtn(page).click()
    await expect(dlg.getByText(/Added \d+ photos?/)).toBeVisible()
    const sent = await page.evaluate(() => (globalThis as { __imports?: { mode: string; options: unknown }[] }).__imports!.at(-1))
    expect(sent).toMatchObject({ mode: 'move', options: { nameTemplate: '{date}_{seq}', folderFormat: 'YYYY/MM/DD' } })
  })
})

test.describe('F26 library: more details and presets', () => {
  const panel = (page: Page) => page.locator('section.panel', { hasText: 'More details' })
  test('LG5 city, country and the other details are under More details, and a preset puts a set of details on the selected photos', async ({ page }) => {
    await open(page)
    await cells(page).first().click()
    const p = panel(page)
    await expect(p.getByLabel('City')).toBeHidden()
    await p.locator('summary', { hasText: 'More details' }).click()
    await p.getByLabel('City').fill('Cape Town')
    await p.getByLabel('City').press('Enter')
    await p.getByLabel('Country').fill('South Africa')
    await p.getByLabel('Country').press('Enter')
    await p.getByLabel('Creator', { exact: true }).fill('Bennett')
    await p.getByLabel('Creator', { exact: true }).press('Enter')
    await p.getByRole('button', { name: 'Keep these details…' }).click()
    await p.getByLabel('Name for this preset').fill('Studio')
    await p.getByRole('button', { name: 'Keep', exact: true }).click()
    await expect(p.getByRole('combobox', { name: 'Detail presets' }).locator('option', { hasText: 'Studio' })).toHaveCount(1)
    // another photo gets them with one choice
    await cells(page).nth(1).click()
    await expect(p.getByLabel('City')).toHaveValue('')
    await p.getByRole('combobox', { name: 'Detail presets' }).selectOption('Studio')
    await expect(p.getByLabel('City')).toHaveValue('Cape Town')
    await expect(p.getByLabel('Creator', { exact: true })).toHaveValue('Bennett')
    // nothing to keep is refused in words
    await cells(page).nth(2).click()
    await p.getByRole('button', { name: 'Keep these details…' }).click()
    await p.getByLabel('Name for this preset').fill('Empty')
    await p.getByRole('button', { name: 'Keep', exact: true }).click()
    await expect(p.getByRole('alert')).toContainText('nothing to keep')
  })
})

test.describe('F26 library: folder tree', () => {
  test('LG6 the folders are a tree: a top line for the place they came from, folders inside, lines that open and close, and the chosen folder shows its photos', async ({ page }) => {
    await open(page)
    const tree = page.getByRole('list', { name: 'Folders' })
    await expect(tree.getByRole('button', { name: 'Demo', exact: false }).first()).toBeVisible()
    const first = tree.getByRole('button', { name: /^2026-10-03/ })
    await expect(first).toBeVisible()
    await first.click()
    await expect(first).toHaveAttribute('aria-current', 'true')
    // the line above the chosen folder cannot be closed on top of it: the chosen folder always stays in view
    await tree.getByRole('button', { name: 'Close Demo' }).click()
    await expect(first).toBeVisible()
    // with nothing chosen it closes, and the folders inside are hidden
    await page.getByRole('button', { name: /^All photographs/ }).click()
    await expect(tree.getByRole('button', { name: /^Studio/ })).toBeHidden()
    await expect(first).toBeHidden()
    await tree.getByRole('button', { name: 'Open Demo' }).click()
    await expect(tree.getByRole('button', { name: /^Studio/ })).toBeVisible()
  })
})
