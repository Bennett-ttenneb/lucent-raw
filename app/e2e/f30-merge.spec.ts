import { expect, open, test } from './helpers'

test.describe('F30 merge and DNG', () => {
  test('MG1 Merge to HDR needs two photos, sends the selection with the alignment choice, and selects the new photo', async ({ page }) => {
    await open(page)
    const cells = page.getByRole('gridcell')
    await cells.nth(0).click()
    await page.getByRole('menuitem', { name: 'Photo' }).click()
    await page.getByRole('menuitem', { name: 'Merge to HDR…' }).click()
    const dlg = page.getByRole('dialog', { name: 'Merge to HDR' })
    await expect(dlg.getByText('Select two or more photos of the same scene')).toBeVisible()
    await expect(dlg.getByRole('button', { name: 'Merge', exact: true })).toBeDisabled()
    await dlg.getByRole('button', { name: 'Cancel' }).click()
    await cells.nth(2).click({ modifiers: ['Shift'] })
    await page.getByRole('menuitem', { name: 'Photo' }).click()
    await page.getByRole('menuitem', { name: 'Merge to HDR…' }).click()
    await expect(dlg.getByText('Merge the 3 selected photos into one.')).toBeVisible()
    await dlg.getByRole('checkbox', { name: /Line the photos up first/ }).uncheck()
    await dlg.getByRole('button', { name: 'Merge', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: /Merged 3 photos into one: IMG_\d+-HDR\.jpg\./ })).toBeVisible()
    const sent = await page.evaluate(() => (globalThis as { __merges?: { ids: number[]; align: boolean }[] }).__merges)
    expect(sent).toHaveLength(1)
    expect(sent![0].align).toBe(false)
    expect(sent![0].ids).toHaveLength(3)
  })

  test('MG2 Merge to panorama sends the selected photos in the order shown and adds the result', async ({ page }) => {
    await open(page)
    const cells = page.getByRole('gridcell')
    await cells.nth(1).click()
    await cells.nth(3).click({ modifiers: ['Shift'] })
    await page.getByRole('menuitem', { name: 'Photo' }).click()
    await page.getByRole('menuitem', { name: 'Merge to panorama…' }).click()
    const dlg = page.getByRole('dialog', { name: 'Merge to panorama' })
    await expect(dlg.getByText('Merge the 3 selected photos into one.')).toBeVisible()
    await expect(dlg.getByRole('checkbox', { name: /Line the photos up/ })).toHaveCount(0)
    await dlg.getByRole('button', { name: 'Merge', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: /Merged 3 photos into one: IMG_\d+-Pano\.jpg\./ })).toBeVisible()
    const sent = await page.evaluate(() => (globalThis as { __panos?: { ids: number[] }[] }).__panos)
    expect(sent![0].ids).toHaveLength(3)
    expect([...sent![0].ids].sort((a, b) => a - b)).not.toEqual([])
  })

  test('DN1 an import can copy RAW photos as DNG (with or without the original inside) and an export can write DNG', async ({ page }) => {
    await open(page)
    await page.getByRole('button', { name: 'Import…' }).click()
    const dlg = page.getByRole('dialog', { name: 'Import photos' })
    await dlg.getByRole('button', { name: 'Choose folder…' }).click()
    await expect(dlg.getByText(/Found 12 photos and 3 RAW files/)).toBeVisible()
    await dlg.getByRole('radio', { name: /Copy as DNG into a folder/ }).check()
    await dlg.getByRole('checkbox', { name: /keep the original RAW file inside each DNG/ }).check()
    await dlg.getByRole('button', { name: 'Choose destination…' }).click()
    await dlg.getByRole('button', { name: /^Import/ }).last().click()
    await expect(dlg.getByText(/Added 15 photos/)).toBeVisible()
    const sent = await page.evaluate(() => (globalThis as unknown as { __imports: { mode: string; options?: { embedOriginal?: boolean } }[] }).__imports.at(-1))
    expect(sent?.mode).toBe('copy_dng')
    expect(sent?.options?.embedOriginal).toBe(true)
    await dlg.getByRole('button', { name: 'Done' }).click()
    await page.getByRole('gridcell').first().click()
    await page.getByRole('button', { name: 'Export…' }).click()
    const exp = page.getByRole('dialog', { name: 'Export photos' })
    await exp.getByLabel('Format').selectOption('dng')
    await expect(exp.getByText(/RAW file is written again as a DNG/)).toBeVisible()
    await expect(exp.getByLabel('Resolution')).toBeDisabled().catch(() => undefined)
  })
  test('SM1 an import can build smart previews for what it adds, and the choice is remembered', async ({ page }) => {
    await open(page)
    await page.getByRole('button', { name: 'Import…' }).click()
    const dlg = page.getByRole('dialog', { name: 'Import photos' })
    await dlg.getByRole('button', { name: 'Choose folder…' }).click()
    await expect(dlg.getByText(/Found 12 photos and 3 RAW files/)).toBeVisible()
    await dlg.getByRole('checkbox', { name: /Also build smart previews/ }).check()
    await dlg.getByRole('button', { name: /^Import/ }).last().click()
    await expect(dlg.getByText(/Added 15 photos/)).toBeVisible()
    await dlg.getByRole('button', { name: 'Done' }).click()
    await page.getByRole('button', { name: 'Preferences' }).click()
    const prefs = page.getByRole('dialog', { name: 'Preferences' })
    await expect(prefs.getByText(/15 photos of 111 have a smart preview/)).toBeVisible()
  })
  test('DN2 AI Denoise sends the open photo with the amount and the ISO and selects the new picture', async ({ page }) => {
    await open(page)
    await page.getByRole('gridcell').nth(2).click()
    await page.getByRole('menuitem', { name: 'Photo' }).click()
    await page.getByRole('menuitem', { name: 'AI Denoise…' }).click()
    const dlg = page.getByRole('dialog', { name: 'AI Denoise' })
    await dlg.getByLabel('Amount').fill('70')
    await dlg.getByLabel('ISO').fill('3200')
    await dlg.getByRole('button', { name: 'Denoise' }).click()
    await expect(page.getByRole('status').filter({ hasText: /Made IMG_\d+-Denoise\.jpg\./ })).toBeVisible()
    const sent = await page.evaluate(() => (globalThis as { __denoise?: { amount: number; iso: number }[] }).__denoise)
    expect(sent![0]).toMatchObject({ amount: 70, iso: 3200 })
  })
  test('FS1 Merge to focus stack takes up to 40 photos in the order shown, with the alignment choice', async ({ page }) => {
    await open(page)
    const cells = page.getByRole('gridcell')
    await cells.nth(0).click()
    await cells.nth(5).click({ modifiers: ['Shift'] })
    await page.getByRole('menuitem', { name: 'Photo' }).click()
    await page.getByRole('menuitem', { name: /Merge to focus stack/ }).click()
    const dlg = page.getByRole('dialog', { name: 'Merge to focus stack' })
    await expect(dlg.getByText('Merge the 6 selected photos into one.')).toBeVisible()
    await dlg.getByRole('button', { name: 'Merge', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: /Merged 6 photos into one: IMG_\d+-Stack\.jpg\./ })).toBeVisible()
    const sent = await page.evaluate(() => (globalThis as { __stacks?: { ids: number[]; align: boolean }[] }).__stacks)
    expect(sent![0]).toMatchObject({ align: true })
    expect(sent![0].ids).toHaveLength(6)
  })
})